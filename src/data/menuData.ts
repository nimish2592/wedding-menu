import { MenuData } from '../types';

function buildCatalogFromEvents(
  events: MenuData['events'],
  baseCatalog: Record<string, string[]>
): Record<string, string[]> {
  const filled: Record<string, string[]> = {};
  for (const cat of Object.keys(baseCatalog)) {
    const items = new Set<string>(baseCatalog[cat]);
    for (const event of events) {
      for (const meal of Object.values(event.meals)) {
        for (const item of (meal?.selection[cat] ?? [])) {
          items.add(item);
        }
      }
    }
    filled[cat] = Array.from(items);
  }
  return filled;
}

